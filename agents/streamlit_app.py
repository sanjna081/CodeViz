def load_dataset_from_upload(uploaded_file) -> pd.DataFrame:
    ext = os.path.splitext(uploaded_file.name)[1].lower()
    if ext == '.csv':
        return pd.read_csv(uploaded_file)
    elif ext in ['.xlsx', '.xls']:
        return pd.read_excel(uploaded_file)
    elif ext == '.json':
        return pd.read_json(uploaded_file)
    elif ext == '.parquet':
        return pd.read_parquet(uploaded_file)
    else:
        raise ValueError(f"Unsupported file format: {ext}")


def display_results(output: dict):
    """Display pipeline results in a clean layout."""

    # Compute stats directly from task_results
    task_results = output.get('task_results', [])
    errors       = output.get('errors', [])

    # ── Subtasks ──────────────────────────────────────────────────────────────
    subtasks = output.get('subtasks', [])
    if subtasks:
        with st.expander("**Subtasks Generated by Planner**", expanded=True):
            for i, t in enumerate(subtasks, 1):
                desc    = t.get('description', str(t)) if isinstance(t, dict) else str(t)
                ml_step = t.get('ml_step') if isinstance(t, dict) else None
                tag     = f" `[{ml_step}]`" if ml_step else ""
                st.markdown(f"**{i}.** {desc}{tag}")

    st.markdown("---")

    # ── Task results ──────────────────────────────────────────────────────────
    if task_results:
        st.markdown("<div class='sub-header'>Task Outputs</div>",
                    unsafe_allow_html=True)

        for idx, t in enumerate(task_results, 1):
            task     = t.get('task', '')
            ok       = t.get('ok', False)
            result   = t.get('result')
            error    = t.get('error')
            code     = t.get('code')
            attempts = t.get('attempts', 1)

            label = f"Task {idx}: {task[:80]}{'...' if len(task) > 80 else ''}"

            with st.expander(f"**{label}**", expanded=ok):
                col1, col2 = st.columns([3, 1])
                with col1:
                    st.write(f"**Agent:** {t.get('agent', '')}")
                    if attempts > 1:
                        st.caption(f"Succeeded after {attempts} attempt(s)")
                with col2:
                    if ok:
                        st.success("✓ Success")
                    else:
                        st.error("✗ Failed")

                if ok and result is not None:
                    if isinstance(result, dict):
                        # Check if it's a visualization result with a file
                        file_path = result.get('file')
                        if file_path and os.path.exists(file_path):
                            st.image(file_path, use_container_width=True)
                        elif file_path and os.path.exists('output.png'):
                            st.image('output.png', use_container_width=True)
                        else:
                            st.json(result)
                    elif isinstance(result, pd.DataFrame):
                        st.dataframe(result, use_container_width=True)
                    else:
                        st.write(result)

                if error:
                    st.error(f"**Error:** {error}")

                if code:
                    with st.expander("View Generated Code"):
                        st.code(code, language='python')

    # ── Errors ────────────────────────────────────────────────────────────────
    if errors:
        st.markdown("---")
        st.markdown("<div class='sub-header'>Pipeline Errors</div>",
                    unsafe_allow_html=True)
        for e in errors:
            st.error(f"**{e.get('task', e.get('stage', 'Unknown'))}**: {e.get('error', '')}")

