def main():
    st.markdown("<div class='main-header'>CodeViz: Multi-Agent Data Science System</div>",
                unsafe_allow_html=True)
    st.markdown("Upload a dataset, describe your problem, and CodeViz will automatically "
                "plan, generate, and execute the full data science pipeline.")
    st.markdown("---")

    # ── Session state ─────────────────────────────────────────────────────────
    if 'df' not in st.session_state:
        st.session_state.df = None
    if 'dataset_name' not in st.session_state:
        st.session_state.dataset_name = None
    if 'analysis_complete' not in st.session_state:
        st.session_state.analysis_complete = False
    if 'results' not in st.session_state:
        st.session_state.results = None

    # ── Sidebar ───────────────────────────────────────────────────────────────
    with st.sidebar:
        st.header("Configuration")

        st.subheader("1. Upload Dataset")
        uploaded_file = st.file_uploader(
            "Choose a file",
            type=['csv', 'xlsx', 'xls', 'json', 'parquet'],
            help="Supported formats: CSV, Excel, JSON, Parquet"
        )

        if uploaded_file is not None:
            try:
                st.session_state.df = load_dataset_from_upload(uploaded_file)
                st.session_state.dataset_name = uploaded_file.name
                st.session_state.analysis_complete = False
                st.success(f"Loaded: {uploaded_file.name}")
            except Exception as e:
                st.error(f"Error loading file: {str(e)}")
                st.session_state.df = None

        if st.session_state.df is not None:
            df = st.session_state.df
            st.markdown("---")
            st.subheader("Dataset Info")
            st.write(f"**Rows:** {df.shape[0]:,}")
            st.write(f"**Columns:** {df.shape[1]}")
            st.write(f"**Columns:** {', '.join(df.columns[:5].tolist())}"
                     + (f" ... +{df.shape[1]-5} more" if df.shape[1] > 5 else ""))

        st.markdown("---")
        use_rag = st.toggle("Use RAG", value=True,
                            help="Enable RAG-augmented planning")

    # ── Main content ──────────────────────────────────────────────────────────
    if st.session_state.df is None:
        st.info("Please upload a dataset to begin.")
        st.markdown("### How it works")
        st.markdown("""
        1. **Upload** your CSV or Excel dataset
        2. **Describe** your data science problem in plain English
        3. **Run** the pipeline (CodeViz plans, generates, and executes the pipeline)
        4. **View** the results, generated code, and metric scores
        """)
        return

    df = st.session_state.df

    # Dataset preview
    st.markdown("### Dataset Preview")
    st.dataframe(df.head(10), use_container_width=True)
    st.markdown("---")

    # Problem statement
    st.markdown("### Problem Statement")
    problem_statement = st.text_area(
        "Describe what you want to do:",
        placeholder=(
            "Example: Train a regression model to predict gemstone price "
            "and report the RMSE score."
        ),
        height=100,
        label_visibility="collapsed"
    )

    st.markdown("---")
    col1, col2 = st.columns([1, 4])
    with col1:
        run_button = st.button("Run Pipeline", type="primary",
                               use_container_width=True,
                               disabled=not bool(problem_statement))
        with col2:
            if st.button("Reset", use_container_width=False):
                st.session_state.analysis_complete = False
                st.session_state.results = None
                st.rerun()

        if run_button:
            st.session_state.analysis_complete = False
            st.session_state.results = None

            # Save uploaded df to a temp CSV for run_analysis_programmatic
            with tempfile.NamedTemporaryFile(
                delete=False, suffix='.csv', mode='w', encoding='utf-8'
            ) as tmp:
                df.to_csv(tmp, index=False)
                tmp_path = tmp.name

            run_name = f"ui_run_{uuid.uuid4().hex[:8]}"

            with st.spinner("Running CodeViz pipeline... this may take 30-90 seconds."):
                try:
                    output = run_analysis_programmatic(
                        dataset_path=tmp_path,
                        problem_statement=problem_statement,
                        use_rag=use_rag,
                        verbose=False,
                        test_case_name=run_name,
                        results_dir=RESULTS_DIR,
                    )
                    st.session_state.results = output
                    st.session_state.analysis_complete = True
                except Exception as e:
                    st.error(f"Pipeline error: {str(e)}")
                finally:
                    if os.path.exists(tmp_path):
                        os.remove(tmp_path)

            if st.session_state.analysis_complete:
                errors = st.session_state.results.get('errors', [])
                if errors:
                    st.warning("Pipeline completed with errors. See details below.")
                else:
                    st.success("Pipeline complete!")
                #st.rerun()

    # Display results
    if st.session_state.analysis_complete and st.session_state.results:
        st.markdown("---")
        display_results(st.session_state.results)


if __name__ == "__main__":
    main()